#!/usr/bin/env python3
"""Ionization potentials of Fe II - Fe VIII from saved total energies (Paper A).

Reads results/energies.csv and the run manifests written by calculate_energies.py.
It never imports FAC and never launches a calculation; a missing energy is reported,
not recomputed, replaced or guessed.

    I_q(mu) = [E(Fe q+1, mu) - E(Fe q, mu)]            (same model, same mu, same build)

Outputs (in --output-dir, default = the results directory):
    ionization_potentials.csv   one row per ionization x model x mu
    comparison_summary.md       literature comparison, shifts and error statistics

Exit code 0 = complete and valid, 2 = missing / invalid / incompatible energies
(the tables are still written, with the problems listed; use --allow-incomplete to get 0).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "shared"))
sys.path.insert(0, str(HERE))

import analysis_support as an        # noqa: E402
import configurations as cfg         # noqa: E402
import reference_data as ref         # noqa: E402

CSV_FIELDS = ["ionization", "ion", "orbital_optimization_model", "case", "mu", "ip_calc_eV",
              "ip_paper_table2_eV", "diff_vs_paper_eV", "rel_diff_vs_paper_percent",
              "ip_nist_eV", "diff_vs_nist_eV", "rel_diff_vs_nist_percent",
              "shift_calc_eV", "shift_paper_eV", "shift_diff_eV",
              "energy_lower_eV", "energy_upper_eV", "status"]


def expected_keys() -> set[tuple]:
    return {(ion, cfg.CONFIGURATION_MODEL, model, case)
            for ion in cfg.ION_ORDER for model in cfg.ORBITAL_MODELS for case in cfg.CASES}


def compute_rows(usable: dict) -> list[dict]:
    rows = []
    for k, ion in enumerate(cfg.ION_ORDER[:-1]):
        upper_ion = cfg.ION_ORDER[k + 1]
        for model in cfg.ORBITAL_MODELS:
            ip_at_zero = None
            for case, mu in cfg.CASES.items():
                lo = usable.get((ion, cfg.CONFIGURATION_MODEL, model, case))
                hi = usable.get((upper_ion, cfg.CONFIGURATION_MODEL, model, case))
                row = {"ionization": f"{ion} -> {upper_ion}", "ion": ion, "orbital_optimization_model": model,
                       "case": case, "mu": mu, "ip_paper_table2_eV": ref.PAPER_TABLE2[ion][case],
                       "ip_nist_eV": ref.NIST_IP[ion] if mu == 0 else "", "status": "ok"}
                paper = ref.PAPER_TABLE2[ion][case]
                row["shift_paper_eV"] = round(paper - ref.PAPER_TABLE2[ion]["mu0p00"], 4)
                if lo is None or hi is None:
                    row["status"] = "NOT COMPUTED: missing or invalid energy"
                    rows.append(row)
                    continue
                ip, why = an.ionization_potential(lo, hi)
                if ip is None:
                    row["status"] = f"NOT COMPUTED: {why}"
                    rows.append(row)
                    continue
                row.update({"ip_calc_eV": round(ip, 4), "energy_lower_eV": lo["total_energy"],
                            "energy_upper_eV": hi["total_energy"],
                            "diff_vs_paper_eV": round(ip - paper, 4),
                            "rel_diff_vs_paper_percent": round(100 * (ip - paper) / paper, 3)})
                if mu == 0:
                    ip_at_zero = ip
                    nist = ref.NIST_IP[ion]
                    row.update({"diff_vs_nist_eV": round(ip - nist, 4),
                                "rel_diff_vs_nist_percent": round(100 * (ip - nist) / nist, 3)})
                if ip_at_zero is not None and mu > 0:
                    row["shift_calc_eV"] = round(ip - ip_at_zero, 4)
                    row["shift_diff_eV"] = round(row["shift_calc_eV"] - row["shift_paper_eV"], 4)
                rows.append(row)
    return rows


def report(rows: list[dict], problems: list[str], results_dir: Path, commits: set[str]) -> str:
    out = ["# Fe II - Fe VIII ionization potentials: reduced reference-configuration model",
           "",
           "Generated by `analyze_ionization_potentials.py` from the saved energies; no FAC calculation was run.",
           "",
           "**This is a reduced-model benchmark, not a reproduction of the published MCDF calculation.** Only the",
           "listed reference configurations are used (no single/double excitations); the orbital models `gref`",
           "(orbitals from the ground configuration, primary) and `ref` (orbitals from the average of all references)",
           "are kept separate throughout. Paper values: Deprince et al., A&A 643, A57 (2020), Table 2. NIST values as quoted there.",
           "", "- Energy source: `energies.csv` in the results directory (with the run manifests)",
           f"- FAC source commit(s) in the energy records: {', '.join(sorted(c[:10] for c in commits))}", ""]
    out += ["## Input integrity", ""]
    out += [f"- PROBLEM: {p}" for p in problems] or ["- All 48 expected energies present, unique, converged and consistent with their manifests."]
    bad = [r for r in rows if r["status"] != "ok"]
    out += [f"- PROBLEM: {r['ionization']} {r['orbital_optimization_model']} {r['case']}: {r['status']}" for r in bad]
    out += [""]
    for model in cfg.ORBITAL_MODELS:
        mrows = [r for r in rows if r["orbital_optimization_model"] == model]
        out += [f"## Model `{model}`", "",
                an.md_table(["Ionization", "mu", "IP calc (eV)", "Table 2 (eV)", "diff (eV)", "diff (%)", "NIST (eV)",
                             "diff vs NIST (eV)", "shift calc (eV)", "shift paper (eV)"],
                            [[r["ionization"], r["mu"], an.fmt(r.get("ip_calc_eV")), an.fmt(r["ip_paper_table2_eV"]),
                              an.fmt(r.get("diff_vs_paper_eV")), an.fmt(r.get("rel_diff_vs_paper_percent"), 2),
                              an.fmt(r["ip_nist_eV"] if r["ip_nist_eV"] != "" else None, 3),
                              an.fmt(r.get("diff_vs_nist_eV")), an.fmt(r.get("shift_calc_eV")),
                              an.fmt(r["shift_paper_eV"] if r["mu"] > 0 else None)] for r in mrows]), ""]
        stats = []
        for label, rs, key in (("vs paper, all mu", mrows, "diff_vs_paper_eV"),
                               ("vs paper, mu = 0", [r for r in mrows if r["mu"] == 0], "diff_vs_paper_eV"),
                               ("vs paper, mu = 0.1", [r for r in mrows if r["mu"] == 0.1], "diff_vs_paper_eV"),
                               ("vs paper, mu = 0.25", [r for r in mrows if r["mu"] == 0.25], "diff_vs_paper_eV"),
                               ("vs NIST, mu = 0", [r for r in mrows if r["mu"] == 0], "diff_vs_nist_eV"),
                               ("screening shift vs paper", [r for r in mrows if r["mu"] > 0], "shift_diff_eV")):
            s = an.summary_stats([(f"{r['ionization']} mu={r['mu']}", r.get(key)) for r in rs])
            stats.append([label, s["n"], an.fmt(s["mean_abs"]), an.fmt(s["max_abs"]), s["max_label"], an.fmt(s["mean_signed"])])
        out += [an.md_table(["Comparison", "n", "mean abs (eV)", "max abs (eV)", "where", "mean signed (eV)"], stats), ""]
    out += ["## Notes", "",
            "- Differences against the paper's calculated values and against NIST are different tests: the paper itself deviates from NIST.",
            "- A positive screening shift is not expected; IPs fall with mu. `shift = IP(mu) - IP(0)` within one model.",
            "- Fe VIII -> Fe IX uses the Fe IX reference set of Paper III (A&A 635, A70), calculated with the same method.",
            ""]
    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--results-dir", type=Path, default=HERE / "results")
    ap.add_argument("--output-dir", type=Path, default=None)
    ap.add_argument("--allow-incomplete", action="store_true", help="exit 0 even if energies are missing or invalid")
    args = ap.parse_args()
    results_dir = args.results_dir.resolve()
    out_dir = (args.output_dir or results_dir).resolve()

    try:
        records = an.load_energy_records(results_dir)
    except an.AnalysisError as e:
        print("ERROR:", e)
        return 2
    usable, problems = an.check_integrity(records, expected_keys(), results_dir)
    rows = compute_rows(usable)
    commits = {r["fac_source_commit"] for r in usable.values()}

    out_dir.mkdir(parents=True, exist_ok=True)
    an.write_csv(out_dir / "ionization_potentials.csv", CSV_FIELDS, rows)
    (out_dir / "comparison_summary.md").write_text(report(rows, problems, results_dir, commits))

    n_ok = sum(1 for r in rows if r["status"] == "ok")
    print(f"{len(usable)}/{len(expected_keys())} usable energies, {n_ok}/{len(rows)} IPs computed")
    for p in problems:
        print("PROBLEM:", p)
    for r in rows:
        if r["status"] != "ok":
            print("PROBLEM:", r["ionization"], r["orbital_optimization_model"], r["case"], r["status"])
    print("wrote", out_dir / "ionization_potentials.csv", "and", out_dir / "comparison_summary.md")
    incomplete = bool(problems) or n_ok != len(rows)
    return 0 if (args.allow_incomplete or not incomplete) else 2


if __name__ == "__main__":
    sys.exit(main())
